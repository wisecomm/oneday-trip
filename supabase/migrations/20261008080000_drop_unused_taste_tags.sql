-- 취향 태그를 장소에 실제로 붙는 다섯으로 줄인다
--
-- 남기는 것: 카페 · 오마카세 · 주차가능 · 심야영업 · 디저트 — 수집 스크립트
-- (load.mjs 의 tagsOf)가 장소에 붙이는 태그와 같다.
--
-- 빼는 것: 비건 · 노포 · 뷰맛집 · 가성비 · 혼밥 · 로컬맛집. 장소에 붙일 근거가 없거나
-- (가성비 · 로컬맛집 · 혼밥) 소개 글 추정뿐이라(비건 · 노포 · 뷰맛집) 붙이지 않아,
-- 회원이 골라도 추천에 반영되지 않는 선택지였다. 반려견 동반을 뺄 때
-- (20261008070000)와 같은 이유다. 화면 선택지에서 빼고 저장된 값도 지운다.
update public.profiles
   set taste_tags = array(
         select t from unnest(taste_tags) as t
          where t <> all (array['비건', '노포', '뷰맛집', '가성비', '혼밥', '로컬맛집'])
       )
 where taste_tags && array['비건', '노포', '뷰맛집', '가성비', '혼밥', '로컬맛집'];
