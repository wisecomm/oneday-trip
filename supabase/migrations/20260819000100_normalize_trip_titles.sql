-- =====================================================================
-- 기간 기반으로 자동 생성됐던 여행 제목을 당일치기 표기로 정리
--
-- 제목은 생성 시점에 '{목적지} {N}박 {N}일' 형태로 굳어져 저장된다.
-- 단일 날짜 모델로 바꾼 뒤에도 이 값이 남아 있으면 하루짜리 여행에
-- '2박 3일'이 붙는 모순이 화면에 그대로 노출된다.
--
-- 사용자가 직접 바꾼 제목까지 덮어쓰지 않도록, 자동 생성 패턴과 정확히
-- 일치하는 행만 대상으로 한다.
-- =====================================================================

update public.trips
set title = destination || ' 당일치기'
where title ~ '^.+ [0-9]+박 [0-9]+일$'
   or title ~ '^.+ 당일치기$' and title <> destination || ' 당일치기';
