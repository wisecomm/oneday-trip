-- =====================================================================
-- trips.published_plan_id — 이 여행을 공유해 만든 추천 코스
--
-- 근거: intent/2026-09-20-플랜-공유/intent.md 13 Q23
--
-- 공유한 여행에는 '추천 코스 공유' 버튼 대신 '공유 완료'를 보여 준다. 그러려면
-- 여행이 자기가 어느 코스가 됐는지 알아야 한다.
--
-- 연결을 어느 쪽에 둘 것인가가 핵심이다. 예전에는 반대 방향으로
-- shared_plans.source_trip_id 를 두었다가 20261001010000 에서 뺐다. 누구나
-- 읽는 공개 행에 남의 비공개 여행 id 가 실리는 것이 7-D1("공개하는 건
-- 동선이지 일기가 아니다")과 어긋났기 때문이다. 내용은 RLS 가 막아도 두
-- 코스가 같은 여행에서 나왔다는 사실은 밖에서 알 수 있었다.
--
-- 이번에는 비공개 쪽에 둔다. trips 는 주인만 읽고 쓰므로(RLS) 이 값은
-- 밖으로 나가지 않는다. 코스 쪽에서는 이 연결이 보이지 않는다.
--
-- 코스가 지워지면 null 이 되어 버튼이 다시 나타난다. 다시 공유하고 싶으면
-- '내가 올린 코스'에서 지우고 새로 공유하면 된다 — publishFromTrip 은 기존
-- 코스를 갱신하지 않고 새로 만들므로, 이 연결이 없으면 같은 여행에서 나온
-- 코스가 두 개가 되는 것을 막을 방법이 없었다.
--
-- 인덱스는 외래키 쪽에 둔다. 코스를 지울 때 trips 를 통째로 훑지 않게
-- (REVIEW-08 2번과 같은 이유).
--
-- 이 컬럼이 생기기 전에 공유한 여행은 연결을 되살릴 수 없다 — 그 정보를
-- 지운 것이 위의 이유다. 그런 여행은 버튼이 그대로 보인다.
-- =====================================================================

alter table public.trips
  add column published_plan_id uuid references public.shared_plans on delete set null;

create index trips_published_plan_idx on public.trips (published_plan_id);
